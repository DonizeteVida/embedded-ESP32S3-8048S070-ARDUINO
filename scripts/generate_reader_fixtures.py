def image(number, color, fmt='JPEG', progressive=False):
    im=Image.new('RGB',(480,800),color)
    draw=ImageDraw.Draw(im)
    draw.rectangle((0,0,479,799),outline='white',width=4)
    draw.rectangle((25,90,455,710),outline='white',width=3)
    draw.text((65,200),f'COMIC TEST PAGE {number}',fill='white',stroke_width=1)
    draw.text((50,260),'Turn board clockwise for portrait',fill='white')
    for x,y in [(35,35),(444,35),(35,764),(444,764),(240,400)]:
        draw.ellipse((x-12,y-12,x+12,y+12),outline='white',width=3)
    output=io.BytesIO();im.save(output,format=fmt,quality=80,progressive=progressive)
    return output.getvalue()

def archive(name, entries, compression=zipfile.ZIP_DEFLATED):
    output=io.BytesIO()
    with zipfile.ZipFile(output,'w',compression=compression) as z:
        for path,data in entries:
            info=zipfile.ZipInfo(path,(2026,1,1,0,0,0));info.compress_type=compression
            z.writestr(info,data)
    data=output.getvalue();(root/name).write_bytes(data);return data

